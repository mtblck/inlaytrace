/**
 * Turns the official VTracer 1.0 npm package into a browser ES module.
 *
 * @visioncortex/vtracer is published as a wasm-pack `--target nodejs` build:
 * the wasm itself is target-independent, but its glue reads the binary with
 * `fs.readFileSync` and exports through CommonJS, so it cannot load in a
 * browser or a worker. Rebuilding with `wasm-pack --target web` would be the
 * tidy fix, but that needs the wasm32 Rust toolchain on every machine that
 * builds this. Rewriting the glue needs nothing beyond Node.
 *
 * The rewrite is three mechanical substitutions. Each one asserts it matched
 * exactly where expected, so a future package version that changes shape fails
 * the build here rather than shipping a module that throws at runtime.
 *
 * Output (gitignored, regenerated on every dev/build):
 *   apps/app/src/engine/vtracer/vtracer.js   ESM glue exporting init() + vectorize_rgba()
 *   apps/app/src/engine/vtracer/vtracer.wasm the unmodified binary
 */
import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const pkgDir = dirname(require.resolve('@visioncortex/vtracer/package.json'))
const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'))

const EXPECTED_VERSION = '1.0.0-alpha.4'
if (pkg.version !== EXPECTED_VERSION) {
  fail(
    `@visioncortex/vtracer is ${pkg.version}, this script was written against ${EXPECTED_VERSION}.\n` +
      '    Check the glue in pkg/vtracer_wasm.js still matches the substitutions below, then bump EXPECTED_VERSION.',
  )
}

let glue = readFileSync(join(pkgDir, 'pkg/vtracer_wasm.js'), 'utf8')

// 1. CommonJS exports → collected names for one ESM export at the end.
const exported = []
glue = glue.replace(/^exports\.(\w+) = \1;$/gm, (_, name) => {
  exported.push(name)
  return ''
})
if (!exported.includes('vectorize_rgba')) fail('Did not find `exports.vectorize_rgba`.')

// 2. Synchronous fs-based instantiation → an async init() taking a URL.
const loader =
  /const wasmPath = `\$\{__dirname\}\/vtracer_wasm_bg\.wasm`;\nconst wasmBytes = require\('fs'\)\.readFileSync\(wasmPath\);\nconst wasmModule = new WebAssembly\.Module\(wasmBytes\);\nlet wasmInstance = new WebAssembly\.Instance\(wasmModule, __wbg_get_imports\(\)\);\nlet wasm = wasmInstance\.exports;\nwasm\.__wbindgen_start\(\);/
if (!loader.test(glue)) fail('The fs-based loader block has changed shape.')
glue = glue.replace(
  loader,
  `let wasm;
let ready;
/** Instantiate once; later calls return the same promise. */
export function init(url) {
  ready ??= WebAssembly.instantiateStreaming(fetch(url), __wbg_get_imports()).then(({ instance }) => {
    wasm = instance.exports;
    wasm.__wbindgen_start();
  });
  return ready;
}`,
)

// 3. Nothing Node-specific may survive.
for (const token of ['require(', '__dirname', 'module.exports', 'exports.']) {
  if (glue.includes(token)) fail(`Node-only token \`${token}\` still present after rewrite.`)
}

glue =
  `// Generated by scripts/vendor-vtracer.mjs from @visioncortex/vtracer@${pkg.version} (${pkg.license}). Do not edit.\n` +
  glue +
  `\nexport { ${exported.join(', ')} };\n`

const out = join(root, 'apps/app/src/engine/vtracer')
mkdirSync(out, { recursive: true })
writeFileSync(join(out, 'vtracer.js'), glue)
copyFileSync(join(pkgDir, 'pkg/vtracer_wasm_bg.wasm'), join(out, 'vtracer.wasm'))
writeFileSync(
  join(out, 'vtracer.d.ts'),
  `export function init(url: string | URL): Promise<void>
export function vectorize_rgba(data: Uint8Array, width: number, height: number, options: object): string
export function vectorize_bytes(data: Uint8Array, options: object): string
`,
)
console.log(`  VTracer ${pkg.version} vendored for the browser (${exported.join(', ')}).`)

function fail(message) {
  console.error(`\n  vendor-vtracer\n\n    ${message}\n`)
  process.exit(1)
}
